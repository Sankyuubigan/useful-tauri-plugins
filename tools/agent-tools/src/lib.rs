//! сам (с согласия пользователя), чтобы решать задачи, недоступные дешёвому
//! рабочему агенту.
//!
//! Архитектура намеренно расширяемая: [`tools`] — реестр инструментов, каждый
//! инструмент — самостоятельный модуль со своим CLI, состоянием и клиентом.
//! Новый инструмент = новый файл в `tools/` + одна строка в реестре; `main.rs`
//! о диспетчеризации не знает.
//!
//! Первый инструмент — [`tools::consult`]: эскалация отчёта рабочего агента к
//! умной модели через OpenAI-совместимый шлюз 9Router, с жёстким лимитом
//! вызовов и принудительной остановкой агента кодом возврата.

