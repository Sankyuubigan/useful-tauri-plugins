//! Метка времени сборки индекса.
//!
//! Отдельный модуль ради одного вызова: так агент, читающий вывод `index`,
//! видит, что метка пришла из часов с датой, а не собрана склейкой строк.

use chrono::Local;

/// Текущее время в формате `ГГГГ-ММ-ДД ЧЧ:ММ:СС` по локальному времени.
///
/// Локальное, а не UTC: пользователь сравнивает метку со своей файловой
/// системой, и расхождение в часах там выглядит как ошибка инструмента.
pub fn now() -> String {
    Local::now().format("%Y-%m-%d %H:%M:%S").to_string()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn stamp_has_the_agreed_shape() {
        let stamp = now();
        assert_eq!(stamp.len(), 19, "неверный формат метки: {stamp}");
        assert!(
            stamp.as_bytes()[4] == b'-' && stamp.as_bytes()[7] == b'-' && stamp.as_bytes()[13] == b':',
            "неверный формат метки: {stamp}"
        );
    }
}